export function AccessoryCategoryIcon({
  category,
  className = "h-5 w-5",
}: {
  category: AccessoryCategoryId;
  className?: string;
}) {
  switch (category) {
    case "monitors":
      return <MonitorIcon className={className} />;
    case "mice":
      return <MouseIcon className={className} />;
    case "keyboards":
      return <KeyboardIcon className={className} />;
    case "headsets":
      return <HeadsetIcon className={className} />;
    case "desk-mats":
      return <DeskMatIcon className={className} />;
    case "power-adaptors":
      return <PowerIcon className={className} />;
    case "other":
      return <OtherIcon className={className} />;
    default:
      return null;
  }
}

